function emitFireboltServiceManagerInterface(): string[] {
  return [
    `/** FireboltServiceManager global interface injected by WPE WebKit extension */`,
    `interface FireboltServiceManager {`,
    `  /** Version of the Firebolt SDK */`,
    `  readonly version: string;`,
    `  /** Get the Firebolt client instance */`,
    `  get(): Promise<FireboltClient>;`,
    `}`,
  ];
}

function emitFireboltClientInterface(modules: Module[]): string[] {
  const lines: string[] = [
    `/** Firebolt client with all module namespaces */`,
    `interface FireboltClient {`,
  ];

  for (const mod of modules) {
    lines.push(`  ${mod.name}: Firebolt.${mod.name}Module;`);
  }

  lines.push(`  /** Cleanup and close connection */`);
  lines.push(`  cleanup(): void;`);
  lines.push(`}`);

  return lines;
}

function emitFireboltServiceManagerGlobal(): string[] {
  return [
    `/** Global FireboltServiceManager injected by WPE WebKit extension */`,
    `declare global { const FireboltServiceManager: FireboltServiceManager; }`,
  ];
}

function emitExportStatements(): string[] {
  return [
    `export { FireboltClient };`,
  ];
}

