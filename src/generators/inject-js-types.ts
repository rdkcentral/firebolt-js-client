/**
 * inject-js-types TypeScript definition generator.
 *
 * Emits a single TypeScript definition file (firebolt-inject.d.ts) that matches
 * the inject-js factory/builder pattern, enabling VS Code intellisense and API
 * documentation for app developers.
 *
 * Only web-platform modules (platform: "web" | "both") are included.
 */

import {
  CanonicalAST,
  Module,
  TypeDecl,
  Method,
  Param,
  TypeRef,
  OptionalRef,
  PrimitiveRef,
  NamedRef,
  ArrayRef,
  ObjectTypeDecl,
} from "../ast/types";
import { GenConfig, GeneratorOutput, registerFullASTGenerator, extractConstraints, formatConstraintNote } from "./index";
import { loadAllSpecs, SpecModuleData, findMethodSpec } from "./spec-reader";

// ---------------------------------------------------------------------------
// Entry point
// ---------------------------------------------------------------------------

function generate(ast: CanonicalAST, _config: GenConfig): GeneratorOutput[] {
  const lines: string[] = [];

  // Load spec data for enhanced JSDoc generation
  const specData = loadAllSpecs();

  lines.push(`// Auto-generated by firebolt-gen — do not edit manually.`);
  lines.push(`// TypeScript definitions for FireboltServiceManager global pattern`);
  lines.push(``);

  // Filter to web + both platform modules only
  const webModules = ast.modules.filter(
    (m) => m.platform === "web" || m.platform === "both"
  );

  // Emit module namespaces
  for (const mod of webModules) {
    const moduleSpec = specData.get(mod.name);
    lines.push(...emitModuleNamespace(mod, ast, moduleSpec));
    lines.push(``);
  }

  // Emit module interfaces
  for (const mod of webModules) {
    const moduleSpec = specData.get(mod.name);
    lines.push(...emitModuleInterface(mod, moduleSpec));
    lines.push(``);
  }

  // Emit FireboltClient interface
  lines.push(...emitFireboltClientInterface(webModules));
  lines.push(``);

  // Emit FireboltServiceManager interface
  lines.push(...emitFireboltServiceManagerInterface());
  lines.push(``);

  // Emit global FireboltServiceManager declaration
  lines.push(...emitFireboltServiceManagerGlobal());
  lines.push(``);

  // Emit export statements
  lines.push(...emitExportStatements());
  lines.push(``);
  lines.push(`// Export Firebolt namespace for direct consumption`);
  lines.push(`export as namespace Firebolt;`);

  return [
    {
      filePath: "inject-js/firebolt-inject.d.ts",
      content: lines.join("\n"),
    },
  ];
}

