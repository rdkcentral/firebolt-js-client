function emitModuleNamespace(module: Module, ast: CanonicalAST, moduleSpec?: SpecModuleData): string[] {
  const lines: string[] = [
    `declare namespace Firebolt {`,
    `  namespace ${module.name} {`,
  ];

  // Emit type declarations (enums, interfaces)
  for (const decl of module.types) {
    const typeLines = emitTypeDecl(decl);
    for (const line of typeLines) {
      lines.push(`    ${line}`);
    }
    lines.push(``);
  }

  // Emit parameter interfaces for methods with parameters
  for (const method of module.methods) {
    // Skip native-only methods when generating for web
    if (method.platform === "native") continue;

    if (method.kind === "call" && method.params.length > 0) {
      const paramInterface = emitParamInterface(method);
      if (paramInterface.length > 0) {
        for (const line of paramInterface) {
          lines.push(`    ${line}`);
        }
        lines.push(``);
      }
    }
  }

  // Emit method signatures
  for (const method of module.methods) {
    // Skip native-only methods when generating for web
    if (method.platform === "native") continue;

    const methodLines = emitMethod(method, module.name, ast, moduleSpec);
    for (const line of methodLines) {
      lines.push(`    ${line}`);
    }
    lines.push(``);
  }

  lines.push(`  }`);
  lines.push(`}`);

  return lines;
}

