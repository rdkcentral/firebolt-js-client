function isPrimitiveWrapPattern(method: Method, moduleName: string, ast: CanonicalAST): boolean {
  if (method.params.length !== 1) {
    return false;
  }
  const param = method.params[0];
  if (param.type.kind !== "named") {
    return false;
  }

  const namedRef = param.type as NamedRef;

  // Find the module in the AST
  const module = ast.modules.find(m => m.name === moduleName);
  if (!module) {
    return false;
  }

  // Find the type declaration
  const typeDecl = module.types.find(t => t.name === namedRef.name);
  if (!typeDecl || typeDecl.kind !== "object") {
    return false;
  }

  // Check for single primitive property
  if (typeDecl.properties.length !== 1) {
    return false;
  }

  const prop = typeDecl.properties[0];
  if (!prop.required || prop.type.kind !== "primitive") {
    return false;
  }

  return true;
}

function findTypeDeclInModule(method: Method, moduleName: string, ast: CanonicalAST): TypeDecl | null {
  const module = ast.modules.find(m => m.name === moduleName);
  if (!module) {
    return null;
  }

  const param = method.params[0];
  if (param.type.kind !== "named") {
    return null;
  }

  const namedRef = param.type as NamedRef;
  return module.types.find(t => t.name === namedRef.name) || null;
}

function getParamInterfaceName(method: Method): string {
  // Capitalize first letter of method name
  const capitalizedMethod = method.name.charAt(0).toUpperCase() + method.name.slice(1);
  return `${capitalizedMethod}Params`;
}

function emitParamInterface(method: Method): string[] {
  if (method.params.length === 0) {
    return [];
  }

  const interfaceName = getParamInterfaceName(method);
  const lines: string[] = [];

  lines.push(`/** Parameters for ${method.name} */`);
  lines.push(`interface ${interfaceName} {`);

  for (const param of method.params) {
    const isOptional = param.type.kind === "optional";
    const opt = isOptional ? "?" : "";
    const ref = isOptional
      ? (param.type as OptionalRef).inner
      : param.type;
    const inner = typeRefToTS(ref);
    const c = extractConstraints(ref);
    if (c) lines.push(`  /** Constraints: ${formatConstraintNote(c)} */`);
    lines.push(`  ${param.name}${opt}: ${inner};`);
  }

  lines.push(`}`);
  return lines;
}


function emitTypeDecl(decl: TypeDecl): string[] {
  if (decl.kind === "enum") {
    return emitEnum(decl);
  }
  if (decl.kind === "object") {
    return emitObject(decl);
  }
  return [`// [unsupported TypeDecl kind: ${decl.kind}]`];
}

function emitEnum(decl: TypeDecl): string[] {
  const literals = (decl as any).values.map((v: any) => `"${v.serializedId}"`).join(" | ");
  const lines: string[] = [];
  if (decl.description) {
    lines.push(`/** ${decl.description} */`);
  }
  lines.push(`type ${decl.name} = ${literals};`);
  return lines;
}

function emitObject(decl: ObjectTypeDecl): string[] {
  const lines: string[] = [];
  if (decl.description) {
    lines.push(`/** ${decl.description} */`);
  }
  lines.push(`interface ${decl.name} {`);
  for (const prop of decl.properties) {
    const opt = !prop.required ? "?" : "";
    const ref =
      !prop.required && prop.type.kind === "optional"
        ? (prop.type as OptionalRef).inner
        : prop.type;
    const inner = typeRefToTS(ref);
    const c = extractConstraints(ref);
    if (c) lines.push(`  /** Constraints: ${formatConstraintNote(c)} */`);
    lines.push(`  ${prop.name}${opt}: ${inner};`);
  }
  lines.push(`}`);
  return lines;
}

